import { useState } from 'react';
import { motion } from 'motion/react';
import { 
  ArrowLeft, 
  Download, 
  Globe, 
  Building2, 
  Search, 
  MessageSquare, 
  Share2, 
  Check, 
  Sparkles,
  Zap
} from 'lucide-react';
import { IndustryData, FrictionCategory } from '../data/mockData';
import { Heatmap } from './Heatmap';
import { Scorecard } from './Scorecard';
import { FrictionList } from './FrictionList';
import { WebsiteAuditPanel } from './WebsiteAuditPanel';
import { FrictionChatbot } from './FrictionChatbot';
import { TrendChart } from './TrendChart';
import { RevenueImpactCard } from './RevenueImpactCard';

interface DashboardProps {
  data: IndustryData;
  onBack: () => void;
}

export function Dashboard({ data, onBack }: DashboardProps) {
  const [selectedCategory, setSelectedCategory] = useState<FrictionCategory | null>(null);
  const [isChatOpen, setIsChatOpen] = useState(false);
  const [chatTopic, setChatTopic] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  const handleExport = () => {
    const reportText = `FRICTIONMAP OS - EXECUTIVE DIAGNOSTIC REPORT
===================================================
Target: ${data.targetUrl || data.targetName || data.companyName || data.industry}
Scan Mode: ${data.scanType || 'Industry'}
Operational Efficiency Score: ${data.efficiencyScore} / 100
Estimated Annual Revenue Leak: $${data.revenueLeak.toLocaleString()}
Potential 12-Month Recovery: $${data.potentialRecovery.toLocaleString()}

HIGH IMPACT FRICTION POINTS:
${data.frictionPoints
  .map(
    (p, i) =>
      `${i + 1}. [${p.category.toUpperCase()}] ${p.problem}
   Cause: ${p.cause}
   Severity: ${p.severity} | Opportunity ROI Score: ${p.opportunityScore}/100
   Recommended Tool: ${p.suggestedTool} (${p.suggestedSolution})
   Action: ${p.actionDetails || 'Automate and streamline'}
`
  )
  .join('\n')}

Generated by FrictionMap OS (The Business Friction Intelligence Platform)
`;

    const blob = new Blob([reportText], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `frictionmap-${(data.targetUrl || data.industry).replace(/[^a-zA-Z0-9]/g, '_')}-report.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleShare = () => {
    navigator.clipboard.writeText(window.location.href);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const openChatWithTopic = (topic: string) => {
    setChatTopic(topic);
    setIsChatOpen(true);
  };

  return (
    <div className="mx-auto max-w-5xl pt-6 pb-24 px-4 sm:px-6">
      {/* Top Navigation Bar */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-6 mb-6 border-b border-white/10 gap-4">
        <button
          onClick={onBack}
          type="button"
          className="flex items-center gap-2 text-xs sm:text-sm font-semibold text-zinc-400 hover:text-white transition-colors cursor-pointer self-start sm:self-auto group"
        >
          <ArrowLeft className="w-4 h-4 group-hover:-translate-x-1 transition-transform" />
          Start New Diagnostic Scan
        </button>

        <div className="flex items-center gap-2.5 self-end sm:self-auto">
          <button
            onClick={handleShare}
            type="button"
            className="flex items-center gap-1.5 bg-zinc-900 hover:bg-zinc-800 text-zinc-300 hover:text-white px-3 py-2 rounded-xl text-xs font-semibold border border-white/10 transition-colors cursor-pointer"
            title="Share report"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-zinc-400" /> : <Share2 className="w-3.5 h-3.5" />}
            {copied ? 'Link Copied' : 'Share'}
          </button>

          <button
            onClick={handleExport}
            type="button"
            className="flex items-center gap-1.5 bg-zinc-900 hover:bg-zinc-800 text-zinc-300 hover:text-white px-3.5 py-2 rounded-xl text-xs font-semibold border border-white/10 transition-colors cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 text-zinc-400" />
            Export Executive Report
          </button>

          <button
            onClick={() => setIsChatOpen(true)}
            type="button"
            className="flex items-center gap-1.5 bg-zinc-500 hover:bg-zinc-400 text-zinc-950 px-3.5 py-2 rounded-xl text-xs font-bold transition-all shadow-md shadow-zinc-500/20 cursor-pointer"
          >
            <MessageSquare className="w-3.5 h-3.5" />
            <span>AI Copilot</span>
          </button>
        </div>
      </div>

      {/* Target Identity Title Header */}
      <motion.div
        initial={{ opacity: 0, y: 15 }}
        animate={{ opacity: 1, y: 0 }}
        className="mb-8"
      >
        <div className="flex flex-wrap items-center gap-2 mb-2">
          <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-md text-xs font-bold uppercase tracking-wider bg-zinc-500/10 text-zinc-400 border border-zinc-500/20">
            {data.scanType === 'website' ? (
              <>
                <Globe className="w-3 h-3" />
                Live Website Diagnostic
              </>
            ) : data.scanType === 'company' ? (
              <>
                <Building2 className="w-3 h-3" />
                Company Operational Scan
              </>
            ) : (
              <>
                <Search className="w-3 h-3" />
                Industry Friction Benchmark
              </>
            )}
          </span>

          <span className="text-xs text-zinc-500">
            Sector: <strong className="text-zinc-300">{data.industry}</strong>
          </span>
        </div>

        <h1 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight flex items-center gap-2">
          {data.targetUrl || data.companyName || data.targetName || data.industry}
          <span className="text-zinc-500 font-normal text-lg sm:text-xl">Friction Intelligence</span>
        </h1>
      </motion.div>

      {/* Real Website Technical Audit Panel if scanType is website */}
      {data.websiteAudit && (
        <WebsiteAuditPanel audit={data.websiteAudit} searchSources={data.searchSources} />
      )}

      {/* Scorecard: Operational Score, Annual Leak, Recovery, Readiness Meter */}
      <Scorecard data={data} />

      {/* Revenue Impact Card */}
      <RevenueImpactCard data={data} />

      {/* Interactive Visual Heatmap */}
      <Heatmap
        data={data}
        selectedCategory={selectedCategory}
        onSelectCategory={(cat) => setSelectedCategory(cat)}
      />

      {/* Trend Analysis Chart */}
      <TrendChart data={data} />

      {/* High-Impact Friction Points, 5-Dimension Scoring, Micro Tool Ecosystem */}
      <FrictionList
        data={data}
        filterCategory={selectedCategory}
        onOpenChatWithTopic={openChatWithTopic}
      />

      {/* Floating Copilot Button when chat is closed */}
      {!isChatOpen && (
        <motion.button
          initial={{ opacity: 0, scale: 0.8 }}
          animate={{ opacity: 1, scale: 1 }}
          type="button"
          onClick={() => setIsChatOpen(true)}
          className="fixed bottom-6 right-6 z-40 bg-zinc-500 hover:bg-zinc-400 text-zinc-950 p-3.5 sm:px-4 sm:py-3 rounded-full font-bold shadow-2xl shadow-zinc-500/40 flex items-center gap-2 transition-all hover:scale-105 cursor-pointer"
        >
          <Sparkles className="w-4 h-4" />
          <span className="hidden sm:inline text-xs font-black uppercase tracking-wider">
            Ask Copilot
          </span>
        </motion.button>
      )}

      {/* Interactive Gemini Chatbot Drawer */}
      <FrictionChatbot
        activeScan={data}
        isOpen={isChatOpen}
        onClose={() => setIsChatOpen(false)}
        externalPrompt={chatTopic}
        onClearExternalPrompt={() => setChatTopic(null)}
      />
    </div>
  );
}
